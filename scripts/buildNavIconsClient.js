// Writes public/js/navIconsClient.js from utils/navIcons.js, so pages drawn in the browser (the
// notification list, driver screens, search results) use the same line icons as the server-drawn menus.
// Run: node scripts/buildNavIconsClient.js. tests/navIcons.test.js fails when the file is out of date.
const fs = require("fs");
const path = require("path");
const { NAV_ICONS } = require("../utils/navIcons");

const build = () => `// Generated by scripts/buildNavIconsClient.js from utils/navIcons.js. Do not edit by hand.
// ManagiraNavIcon(name, { size, className }) returns the same Lucide line icon the menus use (20px unless size is given) ("" if unknown).
(function () {
  "use strict";
  var ICONS = ${JSON.stringify(NAV_ICONS, null, 1).replace(/\n\s*/g, " ").replace(/^\{ /, "{\n  ").replace(/", "/g, '",\n  "')};
  window.ManagiraNavIcon = function (name, opts) {
    var body = ICONS[name];
    if (!body) return "";
    opts = opts || {};
    var px = Number(opts.size) || 20;
    var size = ' width="' + px + '" height="' + px + '"';
    var cls = opts.className ? ' class="' + String(opts.className).replace(/[&"<>]/g, "") + '"' : "";
    return '<svg' + cls + size + ' viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + '</svg>';
  };
})();
`;

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, "..", "public", "js", "navIconsClient.js"), build());
  console.log("wrote public/js/navIconsClient.js");
}
module.exports = { build };
